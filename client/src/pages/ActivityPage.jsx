import React, { useState, useEffect } from 'react';
import { api } from '../api/client.js';
import { formatINR, formatDateTime, formatQuantity } from '../utils/formatters.js';
import { History, RefreshCw, Filter } from 'lucide-react';

export function ActivityPage() {
  const [executions, setExecutions] = useState([]);
  const [instrumentFilter, setInstrumentFilter] = useState('');
  const [pagination, setPagination] = useState({ page: 1, totalPages: 1, total: 0 });
  const [loading, setLoading] = useState(true);

  const fetchExecutions = async () => {
    setLoading(true);
    try {
      const params = {
        page: pagination.page,
        limit: 20,
      };
      if (instrumentFilter) params.instrument = instrumentFilter;

      const res = await api.executions.getAll(params);
      if (res?.executions) {
        setExecutions(res.executions);
        setPagination(res.pagination || { page: 1, totalPages: 1, total: 0 });
      }
    } catch (err) {
      console.error('Failed to load executions', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchExecutions();
  }, [instrumentFilter, pagination.page]);

  return (
    <div className="space-y-5">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-white p-4 sm:p-5 rounded-xl border border-[#E2E8F0] shadow-2xs">
        <div>
          <h1 className="text-base font-bold text-[#172B4D] flex items-center gap-2">
            <History className="w-4 h-4 text-[#087F5B]" />
            Trade Executions Blotter
          </h1>
          <p className="text-xs text-[#667085]">
            Immutable trade execution records generated by the deterministic price-time priority matching engine.
          </p>
        </div>

        <button
          onClick={fetchExecutions}
          className="self-start sm:self-auto flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-[#E2E8F0] bg-white text-[#172B4D] hover:bg-[#F8FAFC] text-xs font-medium transition-colors shadow-2xs"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          <span>Refresh</span>
        </button>
      </div>

      {/* Filter and stats */}
      <div className="flex flex-wrap items-center justify-between gap-3 text-xs">
        <div className="flex items-center gap-2">
          <Filter className="w-3.5 h-3.5 text-[#667085]" />
          <input
            type="text"
            placeholder="Filter by symbol (e.g. RELIANCE)"
            value={instrumentFilter}
            onChange={(e) => {
              setInstrumentFilter(e.target.value.toUpperCase());
              setPagination((prev) => ({ ...prev, page: 1 }));
            }}
            className="bg-white border border-[#CBD5E1] rounded-lg px-3 py-1.5 text-xs text-[#172B4D] font-mono placeholder-[#94A3B8] focus:outline-hidden focus:border-[#087F5B] focus:ring-1 focus:ring-[#087F5B]"
          />
        </div>
        <span className="font-mono text-[#667085] text-[11px]">
          Total Matches Recorded: {pagination.total}
        </span>
      </div>

      {/* Mobile Executions Card View (< sm) */}
      <div className="sm:hidden space-y-2.5">
        {executions.length === 0 ? (
          <div className="py-8 text-center text-[#94A3B8] italic bg-white rounded-xl border border-[#E2E8F0] text-xs">
            No trade executions found.
          </div>
        ) : (
          executions.map((exec) => (
            <div
              key={exec.executionId || exec._id}
              className="bg-white border border-[#E2E8F0] rounded-xl p-3.5 shadow-2xs space-y-2"
            >
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <span className="font-bold text-[#172B4D] text-sm font-sans">{exec.instrument}</span>
                  <span
                    className={`inline-flex items-center px-2 py-0.5 rounded font-semibold text-[10px] font-mono ${
                      exec.userSide === 'BUY'
                        ? 'bg-[#E6F4EF] text-[#087F5B] border border-[#A7F3D0]'
                        : 'bg-[#FEE2E2] text-[#D64545] border border-[#FECACA]'
                    }`}
                  >
                    {exec.userSide}
                  </span>
                </div>
                <span className="text-[10px] font-mono text-[#087F5B] font-semibold">
                  {formatINR(exec.notionalPaise)}
                </span>
              </div>

              <div className="grid grid-cols-2 gap-2 bg-[#F8FAFC] p-2.5 rounded-lg border border-[#E2E8F0] text-xs font-mono">
                <div>
                  <span className="text-[10px] text-[#667085] font-sans block">Execution Price</span>
                  <span className="font-semibold text-[#172B4D]">{formatINR(exec.priceInPaise)}</span>
                </div>
                <div>
                  <span className="text-[10px] text-[#667085] font-sans block">Shares Filled</span>
                  <span className="font-semibold text-[#172B4D]">{formatQuantity(exec.quantity)}</span>
                </div>
              </div>

              <div className="flex items-center justify-between pt-1 border-t border-[#F1F5F9] text-[10px] text-[#667085] font-mono">
                <span className="truncate max-w-[130px]">{exec.executionId}</span>
                <span>{formatDateTime(exec.timestamp)}</span>
              </div>
            </div>
          ))
        )}
      </div>

      {/* Desktop & Tablet Executions Table View (>= sm) */}
      <div className="hidden sm:block overflow-x-auto rounded-xl border border-[#E2E8F0] bg-white shadow-2xs min-w-0 max-w-full">
        <table className="w-full text-left text-xs min-w-[750px]">
          <thead className="bg-[#F8FAFC] text-[#667085] uppercase text-[10px] font-mono tracking-wider border-b border-[#E2E8F0]">
            <tr>
              <th className="py-3 px-3.5">Execution Reference</th>
              <th className="py-3 px-3">Instrument</th>
              <th className="py-3 px-3">Your Role</th>
              <th className="py-3 px-3">Execution Price</th>
              <th className="py-3 px-3">Filled Shares</th>
              <th className="py-3 px-3">Notional Obligation</th>
              <th className="py-3 px-3">Aggressor Side</th>
              <th className="py-3 px-3.5 text-right">Timestamp</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-[#E2E8F0] font-mono text-[11px]">
            {executions.length === 0 ? (
              <tr>
                <td colSpan={8} className="py-12 text-center text-[#94A3B8] italic font-sans">
                  No trade executions found.
                </td>
              </tr>
            ) : (
              executions.map((exec) => (
                <tr key={exec.executionId || exec._id} className="hover:bg-[#F8FAFC] transition-colors">
                  <td className="py-2.5 px-3.5 text-[#667085]">
                    {exec.executionId}
                  </td>
                  <td className="py-2.5 px-3 font-bold text-[#172B4D] font-sans">
                    {exec.instrument}
                  </td>
                  <td className="py-2.5 px-3">
                    <span
                      className={`inline-flex items-center px-2 py-0.5 rounded font-semibold text-[10px] ${
                        exec.userSide === 'BUY'
                          ? 'bg-[#E6F4EF] text-[#087F5B] border border-[#A7F3D0]'
                          : 'bg-[#FEE2E2] text-[#D64545] border border-[#FECACA]'
                      }`}
                    >
                      {exec.userSide}
                    </span>
                  </td>
                  <td className="py-2.5 px-3 font-medium text-[#172B4D]">
                    {formatINR(exec.priceInPaise)}
                  </td>
                  <td className="py-2.5 px-3 text-[#172B4D]">
                    {formatQuantity(exec.quantity)}
                  </td>
                  <td className="py-2.5 px-3 text-[#087F5B] font-semibold">
                    {formatINR(exec.notionalPaise)}
                  </td>
                  <td className="py-2.5 px-3 text-[#667085]">
                    {exec.takerSide} Taker
                  </td>
                  <td className="py-2.5 px-3.5 text-right text-[#667085] text-[10px]">
                    {formatDateTime(exec.timestamp)}
                  </td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}
